function buildReviews(product, index) {
  const copy = reviewCopy[product.category];
  return JSON.stringify(
    copy.map((review, reviewIndex) => ({
      name: reviewers[(index + reviewIndex * 3) % reviewers.length],
      rating: reviewIndex === 0 ? 5 : 4,
      title: review.title,
      text: review.text,
      date: reviewIndex === 0 ? "2026-09-18" : "2026-08-02",
    })),
  );
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function splitCsv(value) {
  return (value || "")
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);
}

